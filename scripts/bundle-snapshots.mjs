#!/usr/bin/env node
/**
 * A Worker has no disk, so before `wrangler dev` / `wrangler deploy` this packs what the server
 * reads from disk on Node:
 *
 *   .worker/snapshots.generated.js   every snapshot text file (JSON, guideline markdown) and the
 *                                    server's own content pages, as strings bundled into the Worker
 *   .worker/assets/                  the story baseline PNGs, served to the Worker through its
 *                                    ASSETS binding (too large to bundle on the free plan)
 *
 * Both are gitignored and rebuilt from snapshots/ and src/content/ every time.
 */
import { copyFileSync, mkdirSync, readFileSync, readdirSync, rmSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const snapshots = join(root, 'snapshots');
const out = join(root, '.worker');
const assets = join(out, 'assets');

rmSync(out, { recursive: true, force: true });
mkdirSync(assets, { recursive: true });

function* walk(dir) {
  for (const name of readdirSync(dir)) {
    if (name.startsWith('.')) continue; // .staging-* folders of an interrupted ingest
    const p = join(dir, name);
    if (statSync(p).isDirectory()) yield* walk(p);
    else yield p;
  }
}

const texts = {};
let textBytes = 0;
let pngs = 0;
for (const file of walk(snapshots)) {
  const rel = relative(snapshots, file).split('\\').join('/');
  if (file.endsWith('.png')) {
    mkdirSync(dirname(join(assets, rel)), { recursive: true });
    copyFileSync(file, join(assets, rel));
    pngs++;
  } else {
    texts[rel] = readFileSync(file, 'utf8');
    textBytes += texts[rel].length;
  }
}

const content = {};
for (const name of readdirSync(join(root, 'src', 'content'))) {
  if (name.endsWith('.md')) content[name] = readFileSync(join(root, 'src', 'content', name), 'utf8');
}

writeFileSync(join(out, 'snapshots.generated.js'), `// Generated by scripts/bundle-snapshots.mjs. Do not edit.\nexport const texts = ${JSON.stringify(texts)};\nexport const content = ${JSON.stringify(content)};\n`);
writeFileSync(join(out, 'snapshots.generated.d.ts'), 'export declare const texts: Record<string, string>;\nexport declare const content: Record<string, string>;\n');

console.log(`bundle-snapshots: ${Object.keys(texts).length} text files (${(textBytes / 1e6).toFixed(1)} MB), ${Object.keys(content).length} content pages, ${pngs} baseline PNGs -> .worker/`);
